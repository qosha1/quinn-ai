"""Worker result types for task execution outcomes.

This module provides the WorkerResult dataclass that encapsulates
the outcome of any worker task execution, including success/failure
status, output, error information, and escalation handling.

This is the execution-layer result type optimized for the worker state machine.
For the organizational-layer result type with worker_id, operation, tokens_used,
etc., see shared.core.worker.WorkerResult.
"""

from __future__ import annotations

from dataclasses import dataclass, field
from typing import Any

# Re-export canonical types for discoverability
from shared.core.worker import (
    WorkerResult as CoreWorkerResult,
    WorkerConfig as CoreWorkerConfig,
    WorkerInfo,
    WorkerNode,
)


@dataclass
class WorkerResult:
    """Represents the outcome of a worker task execution.

    This dataclass captures all relevant information about a completed
    task, including whether it succeeded, any output or errors produced,
    and whether the task requires escalation to a higher-level handler.

    Note: This is the execution-layer result. For the organizational-layer
    result with worker_id, operation, cost tracking, etc., see
    shared.core.worker.WorkerResult (available as CoreWorkerResult).

    Attributes:
        succeeded: Whether the task completed successfully.
        output: The output produced by the task (empty string if none).
        error: Error message if the task failed (None if successful).
        needs_escalation: Whether this result requires escalation.
        escalation_reason: Reason for escalation (empty if not needed).
        artifacts: List of file paths to artifacts generated by the task.
        metadata: Additional key-value data associated with the result.
        duration_ms: Execution time in milliseconds (None if not measured).
    """

    succeeded: bool
    output: str = ""
    error: str | None = None
    needs_escalation: bool = False
    escalation_reason: str = ""
    artifacts: list[str] = field(default_factory=list)
    metadata: dict[str, Any] = field(default_factory=dict)
    duration_ms: int | None = None

    @classmethod
    def success(cls, output: str, **kwargs: Any) -> WorkerResult:
        """Create a successful result.

        Args:
            output: The output produced by the successful task.
            **kwargs: Additional fields to set on the result (e.g., artifacts,
                metadata, duration_ms).

        Returns:
            A WorkerResult with succeeded=True and the given output.

        Example:
            >>> result = WorkerResult.success("Task completed", duration_ms=150)
            >>> result.succeeded
            True
            >>> result.output
            'Task completed'
        """
        return cls(succeeded=True, output=output, **kwargs)

    @classmethod
    def failure(cls, error: str, **kwargs: Any) -> WorkerResult:
        """Create a failed result.

        Args:
            error: Description of what went wrong.
            **kwargs: Additional fields to set on the result (e.g., output,
                metadata, duration_ms).

        Returns:
            A WorkerResult with succeeded=False and the given error.

        Example:
            >>> result = WorkerResult.failure("Connection timeout")
            >>> result.succeeded
            False
            >>> result.error
            'Connection timeout'
        """
        return cls(succeeded=False, error=error, **kwargs)

    @classmethod
    def escalate(cls, reason: str, **kwargs: Any) -> WorkerResult:
        """Create a result that requires escalation.

        Use this when a task cannot be completed at the current level
        and needs to be handled by a higher-level component or human.

        Args:
            reason: Explanation of why escalation is needed.
            **kwargs: Additional fields to set on the result. Note that
                'succeeded' defaults to False unless explicitly overridden.

        Returns:
            A WorkerResult with needs_escalation=True and the given reason.

        Example:
            >>> result = WorkerResult.escalate("Requires admin approval")
            >>> result.needs_escalation
            True
            >>> result.escalation_reason
            'Requires admin approval'
        """
        # Default to not succeeded unless explicitly set
        succeeded = kwargs.pop("succeeded", False)
        return cls(
            succeeded=succeeded,
            needs_escalation=True,
            escalation_reason=reason,
            **kwargs,
        )


# Aliases for type compatibility between layers
__all__ = [
    "WorkerResult",
    "CoreWorkerResult",
    "CoreWorkerConfig",
    "WorkerInfo",
    "WorkerNode",
]
